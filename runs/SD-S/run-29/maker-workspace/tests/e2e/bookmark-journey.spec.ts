import { test, expect } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";

test("complete private bookmark journey by keyboard-friendly controls", async ({ page }) => {
  const email = `reader-${Date.now()}@example.com`;
  await page.goto("/register");
  await page.getByLabel("Your name").fill("Test Reader");
  await page.getByLabel("Email address").fill(email);
  await page.getByLabel("Password").fill("CorrectHorse123!");
  await page.getByRole("button", { name: "Create account" }).click();
  await expect(page).toHaveURL(/\/bookmarks/);
  await page.getByLabel("Web address").fill("HTTP://Example.com:80");
  await page.getByLabel("Title").fill("Example reference");
  await page.getByLabel(/Tags/).fill("Reading, useful");
  await page.getByRole("button", { name: "Save bookmark" }).click();
  await expect(page.getByRole("link", { name: /Example reference/ })).toBeVisible();
  await page.getByLabel("Web address").fill("http://EXAMPLE.COM:80");
  await page.getByLabel("Title").fill("Same place again");
  await page.getByRole("button", { name: "Save bookmark" }).click();
  await expect(page.getByText("Already saved — taking you to it.")).toBeAttached();
  await expect(page.locator("article.bookmark-card")).toHaveCount(1);
  await expect(page.locator("article.bookmark-card")).toBeFocused();
  await page.getByPlaceholder("Search your library…").fill("useful");
  await expect(page.getByRole("link", { name: /Example reference/ })).toBeVisible();
  await page.getByRole("button", { name: /Edit Example reference/ }).click();
  await page.getByLabel("Title").fill("Edited reference");
  await page.getByRole("button", { name: "Save changes" }).click();
  await expect(page.getByRole("link", { name: /Edited reference/ })).toBeVisible();
  await page.getByRole("button", { name: /Delete Edited reference/ }).click();
  await expect(page.getByRole("dialog")).toBeVisible();
  await page.keyboard.press("Escape");
  await expect(page.getByRole("dialog")).not.toBeVisible();
  await page.getByRole("button", { name: /Delete Edited reference/ }).click();
  await page.getByRole("button", { name: "Delete bookmark" }).click();
  await expect(page.getByText("Nothing matches that search")).toBeVisible();
  await page.getByRole("button", { name: "Clear search and filters" }).click();
  await expect(page.getByText("A fresh shelf")).toBeVisible();
  const results = await new AxeBuilder({ page: page as never }).analyze();
  expect(results.violations).toEqual([]);
});
